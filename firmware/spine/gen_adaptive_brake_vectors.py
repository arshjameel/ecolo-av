#!/usr/bin/env python3
"""
Regenerate the adaptive brake's shared examples from the Python (TODO 258).

Writes firmware/spine/adaptive_brake_vectors.txt, which both copies of the adaptive brake
check:

  firmware/spine/crates/adaptive-brake/tests/vectors.rs        (the Rust, on the car)
  ros/bringup/aav_description/test/test_adaptive_brake.py      (the Python, in the sim)

Each case sets the car model, the brake's limits and the tuning, then runs ticks: a car
whose brakes are weaker than the model's (a load aboard) is braked by what the adaptive
brake sends, so the run is closed loop, as on the car. Run it after any change to
adaptive_brake.py, then `tools/test.sh`:

  python3 firmware/spine/gen_adaptive_brake_vectors.py
"""

import importlib.util
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
PACKAGE = ROOT / 'ros/bringup/aav_description/aav_description'
OUT = ROOT / 'firmware/spine/adaptive_brake_vectors.txt'


def load(name):
    """Import one module of aav_description by its path (no ROS, no install needed)."""
    spec = importlib.util.spec_from_file_location(f'aav_description.{name}',
                                                  PACKAGE / f'{name}.py')
    module = importlib.util.module_from_spec(spec)
    sys.modules[f'aav_description.{name}'] = module  # dataclasses look it up while loading
    spec.loader.exec_module(module)
    return module


try:   # the installed package (the tests): never load a second copy beside it
    from aav_description import adaptive_brake as ab, car_model
except ImportError:   # plain python3, no workspace sourced
    sys.modules['aav_description'] = type(sys)('aav_description')
    car_model = load('car_model')
    ab = load('adaptive_brake')

HEADER = """\
# The adaptive brake: examples both copies must agree on (TODO 258).
#
# Generated by firmware/spine/gen_adaptive_brake_vectors.py from aav_description's
# adaptive_brake.py. Do not edit.
#
# Checked by:
#   firmware/spine/crates/adaptive-brake/tests/vectors.rs    (the Rust: the car's)
#   ros/bringup/aav_description/test/test_adaptive_brake.py  (the Python: the sim's)
#
# case <name>
# car max_brake brake_lag brake_dead_time drag throttle_dead_time throttle_lag
# limits released touch full safe_max max_hold_time
# tuning filter_time adapt_time min_decel min_speed max_gain rise_rate high_share
# tick throttle brake speed(none: no fresh speed) dt -> brake gain effectiveness capped spent
# reset | reset_stop
"""

CAR_KEYS = ('max_brake', 'brake_lag', 'brake_dead_time', 'drag', 'throttle_dead_time',
            'throttle_lag')
LIMIT_KEYS = ('released', 'touch', 'full', 'safe_max', 'max_hold_time')
TUNING_KEYS = ('filter_time', 'adapt_time', 'min_decel', 'min_speed', 'max_gain',
               'rise_rate', 'high_share')


def num(x):
    """Return a float exactly (repr round-trips), or none."""
    return 'none' if x is None else repr(float(x))


class Run:
    """One case: the adaptive brake, a car with `share` of the model's brake, the lines."""

    def __init__(self, name, car=None, limits=None, tuning=None, share=0.55, speed=2.0):
        self.car = car or car_model.ActuatorConfig()
        self.limits = limits or ab.BrakeLimits()
        self.tuning = tuning or ab.AdaptiveBrakeConfig()
        self.brake = ab.AdaptiveBrake(self.car, self.limits, self.tuning)
        self.share, self.v, self.level = share, speed, 0.0
        self.lines = [f'case {name}',
                      'car ' + ' '.join(num(getattr(self.car, k)) for k in CAR_KEYS),
                      'limits ' + ' '.join(num(getattr(self.limits, k)) for k in LIMIT_KEYS),
                      'tuning ' + ' '.join(num(getattr(self.tuning, k)) for k in TUNING_KEYS)]

    def tick(self, throttle, brake, dt=0.02, speed='car'):
        """One tick; speed 'car' reads the modelled car's, None gives none."""
        seen = self.v if speed == 'car' else speed
        out = self.brake.update(throttle, brake, seen, dt)
        self.lines.append(f'tick {num(throttle)} {num(brake)} {num(seen)} {num(dt)} -> '
                          f'{num(out.brake)} {num(out.gain)} {num(out.effectiveness)} '
                          f'{int(out.capped)} {int(out.spent)}')
        # The real car: its brake lags what was sent, and grips at `share` of the model's.
        self.level = car_model.lag(self.level, out.brake, self.car.brake_lag, dt)
        push = throttle * 1.5 if throttle > 0.0 else 0.0
        a = push - self.level * self.car.max_brake * self.share - self.car.drag * self.v
        self.v = max(0.0, self.v + a * dt)
        return out

    def stop(self, top=0.35, ramp=0.5, dt=0.02, seconds=6.0):
        """Ask for a brake rising to `top` over `ramp` s, held until the car stands."""
        t = 0.0
        while t < seconds and self.v > 0.01:
            self.tick(0.0, min(top, top * t / ramp), dt)
            t += dt

    def push(self, throttle, seconds, dt=0.02):
        for _ in range(round(seconds / dt)):
            self.tick(throttle, 0.0, dt)

    def op(self, word):
        getattr(self.brake, word)()
        self.lines.append(word)


def loaded_stops():
    """Two stops with 150 kg aboard: the first learns, the second starts knowing."""
    r = Run('loaded-stops')
    r.push(0.0, 0.3)
    r.stop()
    r.push(0.6, 3.0)
    r.stop()
    return r.lines


def empty_car():
    """Run the empty car: the model is right, so nothing is added."""
    r = Run('empty-car', share=1.0)
    r.stop()
    return r.lines


def held_too_long():
    """Run a low safe max and a weak brake: capped, then the extra comes off."""
    limits = ab.BrakeLimits(safe_max=1500.0, max_hold_time=1.0)
    r = Run('held-too-long', limits=limits, share=0.25, speed=3.0)
    r.stop(top=0.3, seconds=4.0)
    # Let go and brake again: a new stop may push again.
    r.tick(0.0, 0.0)
    r.stop(top=0.3, seconds=1.0)
    return r.lines


def no_speed():
    """Run with the wheel speed missing (none) or broken (NaN, inf) now and then."""
    r = Run('no-speed')
    r.push(0.0, 0.2)
    for k in range(120):
        brake = min(0.35, 0.35 * k / 25)
        speed = None if k % 17 in (3, 4) else float('nan') if k % 23 == 5 else (
            float('inf') if k == 40 else 'car')
        r.tick(0.0, brake, 0.02, speed)
    return r.lines


def dead_times():
    """Run with dead times and ticks that vary: the delay line grows and shrinks."""
    car = car_model.ActuatorConfig(brake_dead_time=0.07, throttle_dead_time=0.05,
                                   brake_lag=0.25)
    r = Run('dead-times', car=car)
    dts = (0.02, 0.03, 0.01, 0.02, 0.05)
    for k in range(200):
        dt = dts[k % len(dts)]
        r.tick(0.0, min(0.4, 0.4 * k / 30), dt)
    return r.lines


def resets():
    """reset_stop keeps the effectiveness; reset forgets it. Odd inputs are clamped."""
    r = Run('resets')
    r.stop(seconds=2.0)
    r.op('reset_stop')
    r.v = 1.5
    r.stop(seconds=1.0)
    r.op('reset')
    r.v = 1.5
    for brake in (1.4, -0.2, float('nan'), 0.5):
        r.tick(0.0, brake)
    r.tick(0.2, 0.3)
    return r.lines


CASES = (loaded_stops, empty_car, held_too_long, no_speed, dead_times, resets)


def text():
    """Return the whole file."""
    lines = []
    for case in CASES:
        lines += case()
    return HEADER + '\n'.join(lines) + '\n'


if __name__ == '__main__':
    OUT.write_text(text())
    print(f'wrote {OUT.relative_to(ROOT)}')
